#!/usr/bin/env python3
"""Parse an original Xbox XBE header and print a Markdown summary.

Read-only, standard library only. Kernel imports are reported as ordinals;
symbolic names are resolved by the ghidra-xbe loader, not guessed here.

Usage: python3 -I analysis/xbe_header.py path/to/DEFAULT.xbe > reports/XBE_HEADER.md
"""
import hashlib
import struct
import sys

ENTRY_KEYS = {"retail": 0xA8FC57AB, "debug": 0x94859D4B}
THUNK_KEYS = {"retail": 0x5B6D40B6, "debug": 0xEFB1F152}

SECTION_FLAGS = [
    (0x01, "W"),         # writable
    (0x02, "preload"),
    (0x04, "X"),         # executable
    (0x08, "insertfile"),
    (0x10, "head-ro"),
    (0x20, "tail-ro"),
]


def u32(buf, off):
    return struct.unpack_from("<I", buf, off)[0]


def u16(buf, off):
    return struct.unpack_from("<H", buf, off)[0]


class Xbe:
    def __init__(self, data):
        if data[:4] != b"XBEH":
            raise ValueError("not an XBE (missing XBEH magic)")
        self.data = data
        self.base = u32(data, 0x104)
        self.headers_size = u32(data, 0x108)
        self.image_size = u32(data, 0x10C)
        self.sections = self._sections()

    def hdr_off(self, va):
        """File offset of a VA inside the mapped header region."""
        off = va - self.base
        if not 0 <= off < self.headers_size:
            raise ValueError(f"VA {va:#010x} outside header region")
        return off

    def va_to_file(self, va):
        if self.base <= va < self.base + self.headers_size:
            return va - self.base
        for s in self.sections:
            if s["va"] <= va < s["va"] + s["raw_size"]:
                return s["raw"] + (va - s["va"])
        raise ValueError(f"VA {va:#010x} not backed by file data")

    def cstr(self, va):
        off = self.va_to_file(va)
        end = self.data.index(b"\0", off)
        return self.data[off:end].decode("ascii", "replace")

    def _sections(self):
        count = u32(self.data, 0x11C)
        off = self.hdr_off(u32(self.data, 0x120))
        out = []
        for i in range(count):
            p = off + i * 56
            flags, va, vsize, raw, rsize, name_va = struct.unpack_from("<6I", self.data, p)
            out.append({
                "flags": flags, "va": va, "vsize": vsize,
                "raw": raw, "raw_size": rsize, "name_va": name_va,
                "digest": self.data[p + 36:p + 56].hex(),
            })
        for s in out:
            s["name"] = self.cstr(s["name_va"])
        return out

    def in_image(self, va):
        return self.base <= va < self.base + self.image_size

    def decode(self, raw, keys):
        hits = [(kind, raw ^ key) for kind, key in keys.items() if self.in_image(raw ^ key)]
        if len(hits) != 1:
            raise ValueError(f"ambiguous XOR decode of {raw:#010x}: {hits}")
        return hits[0]

    def certificate(self):
        off = self.hdr_off(u32(self.data, 0x118))
        title = self.data[off + 0x0C:off + 0x0C + 80].decode("utf-16-le").split("\0")[0]
        return {
            "title_id": u32(self.data, off + 0x08),
            "title": title,
            "media": u32(self.data, off + 0x9C),
            "region": u32(self.data, off + 0xA0),
            "ratings": u32(self.data, off + 0xA4),
            "disk": u32(self.data, off + 0xA8),
            "version": u32(self.data, off + 0xAC),
        }

    def libraries(self):
        count = u32(self.data, 0x160)
        if not count:
            return []
        off = self.hdr_off(u32(self.data, 0x164))
        out = []
        for i in range(count):
            p = off + i * 16
            name = self.data[p:p + 8].rstrip(b"\0").decode("ascii", "replace")
            major, minor, build, flags = struct.unpack_from("<4H", self.data, p + 8)
            out.append((name, f"{major}.{minor}.{build}", flags))
        return out

    def kernel_ordinals(self, thunk_va):
        off = self.va_to_file(thunk_va)
        ords = []
        while True:
            v = u32(self.data, off)
            if v == 0:
                return ords
            if not v & 0x80000000:
                raise ValueError(f"thunk entry {v:#010x} is not an ordinal import")
            ords.append(v & 0x7FFFFFFF)
            off += 4


def flag_str(flags):
    names = [n for bit, n in SECTION_FLAGS if flags & bit]
    return ",".join(names) or "-"


def main(path):
    with open(path, "rb") as f:
        data = f.read()
    x = Xbe(data)
    entry_kind, entry = x.decode(u32(data, 0x128), ENTRY_KEYS)
    thunk_kind, thunk = x.decode(u32(data, 0x158), THUNK_KEYS)
    if entry_kind != thunk_kind:
        raise ValueError(f"entry key ({entry_kind}) and thunk key ({thunk_kind}) disagree")
    cert = x.certificate()
    ords = x.kernel_ordinals(thunk)
    tls = u32(data, 0x12C)

    print("# XBE header")
    print()
    print("Generated by `analysis/xbe_header.py` (header parse only; no disassembly).")
    print()
    print("| Field | Value |")
    print("|---|---|")
    print(f"| File size | {len(data):,} bytes |")
    print(f"| SHA-256 | `{hashlib.sha256(data).hexdigest()}` |")
    print(f"| Title | {cert['title']} |")
    print(f"| Title ID | `{cert['title_id']:#010x}` |")
    print(f"| Cert version / disk | {cert['version']} / {cert['disk']} |")
    print(f"| Region / media / ratings | `{cert['region']:#x}` / `{cert['media']:#x}` / `{cert['ratings']:#x}` |")
    print(f"| XOR key kind | {entry_kind} |")
    print(f"| Base address | `{x.base:#010x}` |")
    print(f"| Headers size | `{x.headers_size:#x}` |")
    print(f"| Image size | `{x.image_size:#x}` |")
    print(f"| Entry point | `{entry:#010x}` |")
    print(f"| TLS directory | `{tls:#010x}` |" if tls else "| TLS directory | none |")
    print(f"| Kernel thunk table | `{thunk:#010x}` ({len(ords)} imports) |")
    print(f"| Init flags | `{u32(data, 0x124):#x}` |")
    print(f"| Stack commit / heap reserve / heap commit | `{u32(data, 0x130):#x}` / `{u32(data, 0x134):#x}` / `{u32(data, 0x138):#x}` |")
    print()
    print(f"## Sections ({len(x.sections)})")
    print()
    print("| Name | VA | Virtual size | File offset | Raw size | Flags |")
    print("|---|---|---|---|---|---|")
    for s in x.sections:
        print(f"| `{s['name']}` | `{s['va']:#010x}` | `{s['vsize']:#x}` | `{s['raw']:#x}` | `{s['raw_size']:#x}` | {flag_str(s['flags'])} |")
    print()
    libs = x.libraries()
    print(f"## Linked XDK libraries ({len(libs)})")
    print()
    print("| Library | Version | Flags |")
    print("|---|---|---|")
    for name, ver, flags in libs:
        print(f"| `{name}` | {ver} | `{flags:#06x}` |")
    print()
    print(f"## Kernel imports by ordinal ({len(ords)})")
    print()
    print("Names are intentionally not inferred here; resolve with the ghidra-xbe loader.")
    print()
    print("```")
    for i in range(0, len(ords), 16):
        print(" ".join(f"{o:3d}" for o in ords[i:i + 16]))
    print("```")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
